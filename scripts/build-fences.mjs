// Writes syntaxes/slide-ng-fences.tmLanguage.json.
//
// A TextMate injection cannot reach inside the info string of a fenced code block (the part after the language, where
// slide.ng puts `{monaco}`, `{2,3|5|all}` or `[title.ts]`), because the markdown grammar does not tokenize that part
// any further. So this grammar adds its own fence rules that do: one per language below, all with the same shape, plus a
// last rule for any other language. A fence without options is left to the markdown grammar.
//
// Run: node scripts/build-fences.mjs       (the unit tests check that the committed file is up to date)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// [language names used in the fence, grammar scope to embed, name of the embedded block]
const LANGUAGES = [
  [['ts', 'typescript'], 'source.ts', 'typescript'],
  [['tsx'], 'source.tsx', 'typescriptreact'],
  [['js', 'javascript'], 'source.js', 'javascript'],
  [['jsx'], 'source.js.jsx', 'javascriptreact'],
  [['html'], 'text.html.basic', 'html'],
  [['css'], 'source.css', 'css'],
  [['scss'], 'source.css.scss', 'scss'],
  [['json', 'jsonc'], 'source.json', 'json'],
  [['yaml', 'yml'], 'source.yaml', 'yaml'],
  [['md', 'markdown'], 'text.html.markdown', 'markdown'],
  [['sh', 'bash', 'shell', 'zsh'], 'source.shell', 'shellscript'],
  [['py', 'python'], 'source.python', 'python'],
];

// The text after the language must hold `{`, `[` or one of the flag words, otherwise this is a plain fence.
const OPTIONS = '(\\s+(?=[^`\\n]*(?:[{\\[]|\\bmagic-move\\b|\\btwoslash\\b))[^`\\n]*)';

const rule = (language, embed) => ({
  begin: `(^|\\G)(\\s*)(\`{3,}|~{3,})\\s*${language}${OPTIONS}$`,
  beginCaptures: {
    3: { name: 'punctuation.definition.markdown' },
    4: { name: 'fenced_code.block.language.markdown' },
    5: {
      name: 'fenced_code.block.language.attributes.markdown',
      patterns: [{ include: 'text.html.markdown.slide-ng#code-options' }],
    },
  },
  end: '(^|\\G)(\\2|\\s{0,3})(\\3)\\s*$',
  endCaptures: { 3: { name: 'punctuation.definition.markdown' } },
  name: 'markup.fenced_code.block.markdown',
  ...(embed && { contentName: `meta.embedded.block.${embed.block}`, patterns: [{ include: embed.scope }] }),
});

export function buildFences() {
  const patterns = LANGUAGES.map(([names, scope, block]) => rule(`(?i:(${names.join('|')}))`, { scope, block }));
  patterns.push(rule('([\\w+#.-]+)', null)); // any other language: the options are coloured, the code is left plain
  return {
    $comment: 'Generated by scripts/build-fences.mjs. Do not edit by hand.',
    scopeName: 'slide-ng.fences',
    injectionSelector: 'L:text.html.markdown.slide-ng -markup.fenced_code -markup.inline.raw -meta.embedded -comment',
    patterns,
  };
}

export const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../syntaxes/slide-ng-fences.tmLanguage.json');
export const render = () => JSON.stringify(buildFences(), null, 2) + '\n';

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(OUTPUT, render());
